"""Regenerate editable SVG exports and a visual contact sheet from manifest.json.

Run: python3 design/phase3/icons/export.py
No dependencies. All art is original to this repository.
"""

from html import escape
import json
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
data = json.loads((ROOT / "manifest.json").read_text())
out = ROOT / "svg"
out.mkdir(exist_ok=True)

cards = []
for name, icon in data["icons"].items():
    content = "".join(icon["shapes"])
    svg = (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" '
        'viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        f'stroke-width="{data["strokeWidth"]}" stroke-linecap="round" '
        f'stroke-linejoin="round" role="img" aria-label="{escape(icon["title"])}">'
        f'<title>{escape(icon["title"])}</title>{content}</svg>\n'
    )
    ET.fromstring(svg)
    (out / f"{name}.svg").write_text(svg)
    cards.append(f'<figure><div class="glyph">{svg}</div><figcaption>{escape(name)}</figcaption></figure>')

gallery = """<!doctype html><html lang="en"><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Studigo Phase 3 action icons · original SVG specimens</title>
<style>
:root{font-family:system-ui,sans-serif;color:#141b2d;background:#f7f8fb}
body{max-width:1120px;margin:auto;padding:32px}h1{font-size:28px}p{max-width:70ch;line-height:1.5;color:#39435a}
.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(125px,1fr));gap:16px}
figure{margin:0;padding:16px;display:grid;place-items:center;gap:12px;background:white;border:1px solid #e3e7ef;border-radius:16px;box-shadow:0 1px 2px #141b2d0d}
.glyph{display:grid;place-items:center;width:64px;height:64px;border-radius:16px;background:#ddf6f3;color:#09756d}
.glyph svg{width:28px;height:28px}figcaption{font-size:13px;font-weight:700}
.sizes{display:flex;align-items:center;gap:20px;margin:24px 0;padding:16px;background:white;border-radius:16px}
.sizes svg:nth-child(1){width:16px;height:16px}.sizes svg:nth-child(2){width:20px;height:20px}.sizes svg:nth-child(3){width:24px;height:24px}
</style>
<h1>Studigo action and evidence icons</h1>
<p>Original 24 × 24 SVG set for Phase 3. These supplement the existing 20 × 20 mode glyphs; they do not replace the shipped icon system. Labels remain visible beside controls. Each shape inherits currentColor.</p>
<div class="grid">""" + "".join(cards) + """</div>
<div class="sizes">Scale: 16px, 20px, 24px
<svg viewBox="0 0 24 24" fill="none" stroke="#09756d" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">""" + "".join(data["icons"]["source"]["shapes"]) + """</svg>
<svg viewBox="0 0 24 24" fill="none" stroke="#09756d" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">""" + "".join(data["icons"]["source"]["shapes"]) + """</svg>
<svg viewBox="0 0 24 24" fill="none" stroke="#09756d" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">""" + "".join(data["icons"]["source"]["shapes"]) + """</svg></div></html>"""
(ROOT / "specimen.html").write_text(gallery)

# The React glyphs are generated from the same original vector manifest as the
# editable SVGs. Runtime code cannot drift into a different icon family.
target = ROOT.parents[2] / "apps/web/components/phase3/action-glyph.tsx"
entries = []
for name, icon in data["icons"].items():
    entries.append(f'  {name}: <>{"".join(icon["shapes"])}</>,')
component = '''/** Generated by design/phase3/icons/export.py from manifest.json. Do not edit by hand. */
const PATHS = {
''' + "\n".join(entries) + '''
};

export type ActionGlyphName = keyof typeof PATHS;

export function ActionGlyph({ name, size = 20, label }: { name: ActionGlyphName; size?: number; label?: string }) {
  return <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" role={label ? "img" : undefined} aria-label={label} aria-hidden={label ? undefined : true} focusable="false">{PATHS[name]}</svg>;
}
'''
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(component)
print(f"Exported {len(cards)} SVGs, specimen.html and action-glyph.tsx")
